"""Write Sources/SPLMark/MarkTables.generated.swift from spl-core's locked mark assets.

usage: scripts/generate-mark-tables.py <spl-rust checkout>

The tables live in code rather than in a resource bundle so that an app can't ship without them.
Their order is load-bearing, so this keeps each file's order exactly.
"""
import hashlib
import json
import pathlib
import sys

root = pathlib.Path(sys.argv[1]) / "crates/spl-core/assets/mark_assets"
glyphs = json.loads((root / "glyphs.json").read_text("utf-8"))
colors = json.loads((root / "colors.json").read_text("utf-8"))
words = json.loads((root / "words.json").read_text("utf-8"))
assert (len(glyphs), len(colors), len(words)) == (60, 16, 7776)
assert all("\n" not in word and '"""' not in word for word in words)

lines = [
    "// SPDX-License-Identifier: AGPL-3.0-only",
    "// Copyright (c) 2026 sol pbc",
    "//",
    "// Generated by scripts/generate-mark-tables.py from spl-core's locked mark assets. Do not edit.",
    "// See NOTICE.md for the glyph and word list licenses.",
    "// swift-format-ignore-file",
    "",
    "enum MarkTables {",
    "    static let glyphs: [(name: String, svg: String)] = [",
]
for name, svg in glyphs.items():
    lines.append(f'        (name: "{name}", svg: #"{svg}"#),')
lines += [
    "    ]",
    "",
    "    static let colors: [(name: String, hex: String)] = [",
]
for name, value in colors:
    lines.append(f'        (name: "{name}", hex: "{value}"),')
lines += [
    "    ]",
    "",
    "    static let wordList = \"\"\"",
]
lines += ["    " + word for word in words]
lines += [
    '    """',
    "}",
    "",
]
pathlib.Path("Sources/SPLMark/MarkTables.generated.swift").write_text("\n".join(lines), "utf-8")
